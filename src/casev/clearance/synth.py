"""Synthetic incident scenario database for the Mumbai–Pune Expressway (paper Section 4.7).

Real clearance-time records are not publicly available for Indian highways, so
records are sampled from categorical distributions and numeric ranges, and the
clearance time is assigned by a scenario model conditioned on severity,
incident type and lane blockage, with log-normal noise.

IMPORTANT: results on this database show that the estimator works as designed.
They do NOT measure accuracy on real incidents, because the estimator is
evaluated on data generated by a known rule.

Segment coordinates are approximate and for demonstration only.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, List, Tuple

import numpy as np
import pandas as pd

# (name, lat, lon, chainage_km) – approximate positions along the expressway
SEGMENTS: List[Tuple[str, float, float, float]] = [
    ("Kalamboli", 19.020, 73.105, 0.0),
    ("Khalapur Toll", 18.830, 73.280, 33.0),
    ("Adoshi Tunnel", 18.783, 73.373, 44.0),
    ("Amrutanjan Bridge", 18.750, 73.420, 50.0),
    ("Khandala Ghat", 18.720, 73.395, 53.0),
    ("Lonavala Exit", 18.745, 73.420, 56.0),
    ("Talegaon", 18.730, 73.670, 79.0),
    ("Kiwale / Dehu Road", 18.665, 73.735, 94.5),
]
GHAT_SEGMENTS = {"Adoshi Tunnel", "Amrutanjan Bridge", "Khandala Ghat"}

INCIDENT_TYPES: Dict[str, float] = {  # type -> base clearance (minutes)
    "minor collision": 25,
    "rear-end collision": 40,
    "vehicle breakdown": 30,
    "truck brake failure": 70,
    "multi-vehicle pile-up": 150,
    "vehicle fire": 120,
    "tanker overturn": 300,
}
TYPE_PROBS = [0.28, 0.22, 0.18, 0.10, 0.08, 0.07, 0.07]
SEVERITIES = ["low", "moderate", "high"]
SEV_MULT = {"low": 0.7, "moderate": 1.0, "high": 1.8}
WEATHER = ["clear", "cloudy", "rainy", "foggy"]
WEATHER_PROBS = [0.5, 0.2, 0.2, 0.1]
WEATHER_MULT = {"clear": 1.0, "cloudy": 1.05, "rainy": 1.3, "foggy": 1.2}
TRAFFIC = ["low", "medium", "heavy", "very heavy"]
TRAFFIC_MULT = {"low": 0.9, "medium": 1.0, "heavy": 1.15, "very heavy": 1.3}


@dataclass
class SynthConfig:
    n_records: int = 3100
    seed: int = 42
    noise_sigma: float = 0.25  # log-normal noise on clearance time
    location_jitter_km: float = 1.5
    start_date: str = "2018-01-01"
    end_date: str = "2025-12-31"


def _severity_given_type(rng, itype: str) -> str:
    if itype in {"tanker overturn", "multi-vehicle pile-up", "vehicle fire"}:
        p = [0.05, 0.35, 0.60]
    elif itype in {"minor collision", "vehicle breakdown"}:
        p = [0.65, 0.30, 0.05]
    else:
        p = [0.30, 0.45, 0.25]
    return rng.choice(SEVERITIES, p=p)


def clearance_model(itype: str, severity: str, lanes_blocked: int, weather: str, traffic: str,
                    ghat: bool, rng=None, noise_sigma: float = 0.0) -> float:
    """Scenario model used to assign clearance time (minutes)."""
    t = INCIDENT_TYPES[itype] * SEV_MULT[severity]
    t *= 1.0 + 0.35 * lanes_blocked
    t *= WEATHER_MULT[weather] * TRAFFIC_MULT[traffic]
    t *= 1.25 if ghat else 1.0  # restricted access for recovery vehicles on ghat sections
    if rng is not None and noise_sigma > 0:
        t *= rng.lognormal(0.0, noise_sigma)
    return float(max(5.0, t))


def generate(cfg: SynthConfig = SynthConfig()) -> pd.DataFrame:
    rng = np.random.default_rng(cfg.seed)
    t0, t1 = pd.Timestamp(cfg.start_date).value, pd.Timestamp(cfg.end_date).value
    rows = []
    for i in range(cfg.n_records):
        seg, lat, lon, km = SEGMENTS[rng.integers(len(SEGMENTS))]
        jitter = cfg.location_jitter_km / 111.0
        itype = rng.choice(list(INCIDENT_TYPES), p=TYPE_PROBS)
        sev = _severity_given_type(rng, itype)
        vehicles = int({"multi-vehicle pile-up": rng.integers(4, 25)}.get(itype, rng.integers(1, 4)))
        lanes = int(rng.integers(0, 4)) if sev != "low" else int(rng.integers(0, 2))
        weather = rng.choice(WEATHER, p=WEATHER_PROBS)
        traffic = rng.choice(TRAFFIC)
        ghat = seg in GHAT_SEGMENTS
        rows.append({
            "incident_id": f"SYN{i:05d}",
            "timestamp": pd.Timestamp(int(rng.integers(t0, t1))).floor("min"),
            "segment": seg,
            "lat": lat + rng.normal(0, jitter),
            "lon": lon + rng.normal(0, jitter),
            "chainage_km": km,
            "incident_type": itype,
            "severity": sev,
            "vehicles": vehicles,
            "lanes_blocked": lanes,
            "weather": weather,
            "traffic": traffic,
            "clearance_min": round(clearance_model(itype, sev, lanes, weather, traffic, ghat, rng, cfg.noise_sigma), 1),
            "synthetic": True,
        })
    return pd.DataFrame(rows)


def load_seed_records(path: str) -> pd.DataFrame:
    """Seed incidents compiled from public reports (approximate, not official records)."""
    df = pd.read_csv(path)
    df["synthetic"] = False
    return df
